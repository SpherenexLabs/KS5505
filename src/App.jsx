/**
 * The safe-zone editor on a caretaker's patient card.
 *
 * The caretaker picks the centre - usually by standing at the patient's front
 * door and pressing "Use my location" - and the radius. Saving stores the
 * circle and mirrors it into Firebase, and the backend raises an emergency the
 * moment the patient's phone reports a position outside it.
 */
function GeofenceEditor({ patientId, tracking, onSaved }) {
  const fence = tracking?.fence;
  const [form, setForm] = useState({
    lat: fence?.lat ?? "",
    lng: fence?.lng ?? "",
    radius: fence?.radius ?? 150,
    label: fence?.label ?? "Home",
  });
  const [busy, setBusy] = useState(false);
  const [message, setMessage] = useState("");

  // The circle follows the form while it is being edited, so the caretaker
  // sees the boundary they are about to save, not the one already stored.
  const draftCentre =
    form.lat !== "" && form.lng !== "" && Number.isFinite(Number(form.lat))
      && Number.isFinite(Number(form.lng))
      ? { lat: Number(form.lat), lng: Number(form.lng) }
      : null;

  const useMyLocation = async () => {
    setMessage("Reading your phone location...");
    const location = await browserLocation();
    if (!location) {
      setMessage("Allow location permission to use your own position.");
      return;
    }
    setForm((current) => ({
      ...current,
      lat: location.lat.toFixed(6),
      lng: location.lng.toFixed(6),
    }));
    setMessage("Centre set to where you are standing now.");
  };

  const usePatientLocation = () => {
    if (!tracking?.location) {
      setMessage("The patient has not shared a position yet.");
      return;
    }
    setForm((current) => ({
      ...current,
      lat: tracking.location.lat.toFixed(6),
      lng: tracking.location.lng.toFixed(6),
    }));
    setMessage("Centre set to the patient's last known position.");
  };

  const save = async () => {
    setBusy(true);
    setMessage("");
    try {
      const response = await fetch(
        `${API}/api/caregiver/patients/${patientId}/geofence`,
        {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            lat: Number(form.lat),
            lng: Number(form.lng),
            radius: Number(form.radius),
            label: form.label,
          }),
        },
      );
      const data = await response.json();
      if (!response.ok) {
        setMessage(data.error || "Could not save the safe zone.");
        return;
      }
      setMessage(
        data.breached
          ? `Safe zone saved at ${Math.round(data.fence.radius)} m. The patient is already outside it, so an emergency alert has gone out.`
          : `Safe zone saved at ${Math.round(data.fence.radius)} m.`,
      );
      onSaved?.();
    } finally {
      setBusy(false);
    }
  };

  const clear = async () => {
    setBusy(true);
    try {
      await fetch(`${API}/api/caregiver/patients/${patientId}/geofence`, {
        method: "DELETE",
      });
      setMessage("Safe zone removed.");
      onSaved?.();
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="geofence-editor">
      <h4><Route size={16} /> Safe zone (geofence)</h4>

      <GeofenceMap
        centre={draftCentre}
        radius={Number(form.radius) || 0}
        patient={tracking?.location}
        editable
        onCentreChange={(point) =>
          setForm((current) => ({
            ...current,
            lat: point.lat.toFixed(6),
            lng: point.lng.toFixed(6),
          }))
        }
        height={300}
      />

      <RadiusPicker
        value={form.radius}
        onChange={(radius) => setForm((current) => ({ ...current, radius }))}
      />

      <div className="geofence-grid">
        <input
          placeholder="Zone name e.g. Home"
          value={form.label}
          onChange={(event) => setForm({ ...form, label: event.target.value })}
        />
        <input
          placeholder="Latitude"
          value={form.lat}
          onChange={(event) => setForm({ ...form, lat: event.target.value })}
        />
        <input
          placeholder="Longitude"
          value={form.lng}
          onChange={(event) => setForm({ ...form, lng: event.target.value })}
        />
      </div>
      <div className="geofence-actions">
        <button className="outline-btn" onClick={useMyLocation}>
          <LocateFixed size={16} />
          Use my location
        </button>
        <button className="outline-btn" onClick={usePatientLocation}>
          <MapPin size={16} />
          Use patient position
        </button>
        <button onClick={save} disabled={busy || !form.lat || !form.lng}>
          Save safe zone
        </button>
        {fence && (
          <button className="danger-btn" onClick={clear} disabled={busy}>
            <Trash2 size={16} />
            Remove
          </button>
        )}
      </div>
      {message && <p className="section-note">{message}</p>}
    </div>
  );
}

/** Live position, distance from the safe zone, and a small map. */
function PatientTrackingCard({ tracking, caretakerLocation }) {
  const location = tracking?.location;
  const fence = tracking?.fence;
  const outside = tracking?.inside === false;
  const mapUrl = tracking?.mapUrl || "";
  const caretakerDistance =
    location && caretakerLocation
      ? Math.round(
          // Same haversine the backend uses, kept short for one readout.
          2 *
            6371000 *
            Math.asin(
              Math.min(
                1,
                Math.sqrt(
                  Math.sin(
                    ((location.lat - caretakerLocation.lat) * Math.PI) / 360,
                  ) **
                    2 +
                    Math.cos((caretakerLocation.lat * Math.PI) / 180) *
                      Math.cos((location.lat * Math.PI) / 180) *
                      Math.sin(
                        ((location.lng - caretakerLocation.lng) * Math.PI) / 360,
                      ) **
                        2,
                ),
              ),
            ),
        )
      : null;

  return (
    <div className="tracking-card">
      <h4><MapPin size={16} /> Live location</h4>
      {location ? (
        <>
          <div className={`fence-state ${outside ? "danger" : "safe"}`}>
            {outside ? <ShieldAlert size={18} /> : <ShieldCheck size={18} />}
            <span>
              {fence
                ? `${outside ? "Outside" : "Inside"} ${fence.label} · ${formatDistance(tracking.distance)} from centre`
                : "No safe zone set yet"}
            </span>
          </div>
          <GeofenceMap
            centre={fence}
            radius={fence?.radius || 0}
            patient={location}
            caretaker={caretakerLocation}
            height={240}
          />
          <p className="section-note">
            {location.lat.toFixed(5)}, {location.lng.toFixed(5)} · ±
            {Math.round(location.accuracy || 0)} m · {tracking.source || "phone"} ·{" "}
            {location.updatedAt || "just now"}
          </p>
          {caretakerDistance != null && (
            <p className="section-note">
              You are {formatDistance(caretakerDistance)} from the patient.
            </p>
          )}
          <a className="outline-btn" href={mapUrl} target="_blank" rel="noreferrer">
            <Navigation size={16} />
            Open in Maps
          </a>
        </>
      ) : (
        <p className="section-note">
          No position yet. Ask the patient to open their tracking link.
        </p>
      )}
    </div>
  );
}

