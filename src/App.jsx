function getSchedulePeriod(time) {
  const hour = Number(String(time || "09:00").split(":")[0]);
  if (hour >= 5 && hour < 12) return "Morning";
  if (hour >= 12 && hour < 17) return "Afternoon";
  if (hour >= 17 && hour < 22) return "Evening";
  return "Night";
}

function formatScheduleTime(time) {
  const [hourValue, minute = "00"] = String(time || "09:00").split(":");
  const hour = Number(hourValue);
  const meridiem = hour >= 12 ? "PM" : "AM";
  const displayHour = hour % 12 || 12;
  return `${displayHour}:${minute} ${meridiem} - ${getSchedulePeriod(time)}`;
}

function ScheduleTimePicker({ value, onChange }) {
  const [hourValue, minuteValue = "00"] = String(value || "09:00").split(":");
  const hour24 = Number(hourValue);
  const hour12 = hour24 % 12 || 12;
  const meridiem = hour24 >= 12 ? "PM" : "AM";
  const selectedPeriod = getSchedulePeriod(value);

  const updateTime = (nextHour12, nextMinute, nextMeridiem) => {
    let nextHour = Number(nextHour12) % 12;
    if (nextMeridiem === "PM") nextHour += 12;
    onChange(`${String(nextHour).padStart(2, "0")}:${nextMinute}`);
  };

  return (
    <div className="schedule-time-picker">
      <span className="schedule-time-label">Choose time of day</span>
      <div className="schedule-period-options">
        {SCHEDULE_PERIODS.map((period) => (
          <button
            type="button"
            className={selectedPeriod === period.label ? "active" : ""}
            key={period.label}
            onClick={() => onChange(period.time)}
          >
            {period.label}
          </button>
        ))}
      </div>
      <div className="schedule-clock-options">
        <label>
          <span>Hour</span>
          <select
            aria-label="Schedule hour"
            value={hour12}
            onChange={(event) =>
              updateTime(event.target.value, minuteValue, meridiem)
            }
          >
            {Array.from({ length: 12 }, (_, index) => index + 1).map((hour) => (
              <option value={hour} key={hour}>{hour}</option>
            ))}
          </select>
        </label>
        <label>
          <span>Minute</span>
          <select
            aria-label="Schedule minute"
            value={minuteValue}
            onChange={(event) =>
              updateTime(hour12, event.target.value, meridiem)
            }
          >
            {Array.from({ length: 60 }, (_, index) =>
              String(index).padStart(2, "0"),
            ).map((minute) => (
              <option value={minute} key={minute}>{minute}</option>
            ))}
          </select>
        </label>
        <label>
          <span>AM / PM</span>
          <select
            aria-label="AM or PM"
            value={meridiem}
            onChange={(event) =>
              updateTime(hour12, minuteValue, event.target.value)
            }
          >
            <option value="AM">AM</option>
            <option value="PM">PM</option>
          </select>
        </label>
      </div>
    </div>
  );
}

