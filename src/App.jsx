function SimpleVitalsChart({ data }) {
  if (!data || data.length === 0) {
    return (
      <div className="empty-chart">
        No Firebase vitals history available yet.
      </div>
    );
  }

  const maxHR = 130;
  const maxSpO2 = 100;
  const maxTemp = 45;

  const width = 700;
  const height = 260;
  const padding = 30;

  const getX = (index) => {
    if (data.length === 1) return padding;
    return padding + (index * (width - padding * 2)) / (data.length - 1);
  };

  const getY = (value, max) => {
    return height - padding - (value / max) * (height - padding * 2);
  };

  const createPath = (key, max) => {
    return data
      .map((item, index) => {
        const x = getX(index);
        const y = getY(Number(item[key] || 0), max);
        return `${index === 0 ? "M" : "L"} ${x} ${y}`;
      })
      .join(" ");
  };

  return (
    <div className="simple-chart-wrap">
      <svg viewBox={`0 0 ${width} ${height}`} className="simple-chart">
        <line x1={padding} y1={padding} x2={padding} y2={height - padding} className="axis" />
        <line x1={padding} y1={height - padding} x2={width - padding} y2={height - padding} className="axis" />

        <path d={createPath("heartRate", maxHR)} className="chart-line hr-line" />
        <path d={createPath("spo2", maxSpO2)} className="chart-line spo2-line" />
        <path d={createPath("temperature", maxTemp)} className="chart-line temp-line" />

        {data.map((item, index) => (
          <circle
            key={`hr-${index}`}
            cx={getX(index)}
            cy={getY(Number(item.heartRate || 0), maxHR)}
            r="4"
            className="hr-dot"
          />
        ))}

        {data.map((item, index) => (
          <circle
            key={`spo2-${index}`}
            cx={getX(index)}
            cy={getY(Number(item.spo2 || 0), maxSpO2)}
            r="4"
            className="spo2-dot"
          />
        ))}

        {data.map((item, index) => (
          <circle
            key={`temp-${index}`}
            cx={getX(index)}
            cy={getY(Number(item.temperature || 0), maxTemp)}
            r="4"
            className="temp-dot"
          />
        ))}
      </svg>

      <div className="chart-legend">
        <span><b className="legend-dot hr-bg"></b>Heart Rate</span>
        <span><b className="legend-dot spo2-bg"></b>SpO2</span>
        <span><b className="legend-dot temp-bg"></b>Temperature</span>
      </div>
    </div>
  );
}

function ChatBox({ title, type }) {
  const chatBodyRef = useRef(null);
  const recognitionRef = useRef(null);
  const [messages, setMessages] = useState([
    {
      from: "bot",
      text:
        type === "patient"
          ? "Hello, I am your companion care bot. Choose a question below or type your own."
          : "Hello caregiver. Choose a question below or type your own.",
    },
  ]);
  const [text, setText] = useState("");
  const [isSending, setIsSending] = useState(false);
  const [voiceStatus, setVoiceStatus] = useState("Tap the microphone to speak.");
  const [isListening, setIsListening] = useState(false);
  const [alwaysOn, setAlwaysOn] = useState(
    () => localStorage.getItem(`${ALWAYS_LISTEN_KEY}.${type}`) === "on",
  );
  const [wakeWordOnly, setWakeWordOnly] = useState(
    () => localStorage.getItem(`${WAKE_WORD_KEY}.${type}`) !== "off",
  );

  // Callbacks on a running recogniser outlive the render that made them, so
  // anything they read lives in a ref.
  const alwaysOnRef = useRef(alwaysOn);
  const wakeWordOnlyRef = useRef(wakeWordOnly);
  const stoppingRef = useRef(false);
  const speakingRef = useRef(false);
  const restartTimerRef = useRef(null);
  const restartDelayRef = useRef(400);
  const sendMessageRef = useRef(() => {});
  const startRecognitionRef = useRef(() => {});

  useEffect(() => {
    const chatBody = chatBodyRef.current;
    if (chatBody) {
      chatBody.scrollTop = chatBody.scrollHeight;
    }
  }, [messages, isSending]);

  useEffect(() => {
    alwaysOnRef.current = alwaysOn;
    wakeWordOnlyRef.current = wakeWordOnly;
  }, [alwaysOn, wakeWordOnly]);

  useEffect(() => {
    if (!alwaysOn) return undefined;
    if (!recognitionRef.current) {
      startRecognitionRef.current({ manual: false });
    }
    return () => {
      stoppingRef.current = true;
      window.clearTimeout(restartTimerRef.current);
      recognitionRef.current?.abort();
      recognitionRef.current = null;
    };
  }, [alwaysOn]);

  useEffect(() => {
    return () => {
      window.clearTimeout(restartTimerRef.current);
      recognitionRef.current?.abort();
    };
  }, []);

  const speakAnswer = (answer) => {
    if ("speechSynthesis" in window) {
      // Close the microphone first, or always-on listening hears the answer
      // and treats it as the next question.
      speakingRef.current = true;
      pauseListening();
      window.speechSynthesis.cancel();

      const utterance = new SpeechSynthesisUtterance(answer);
      utterance.rate = type === "patient" ? 0.88 : 1;
      utterance.pitch = 1;
      utterance.lang = "en-IN";
      const resumeListening = () => {
        speakingRef.current = false;
        if (alwaysOnRef.current) scheduleListenRestart(600);
      };
      utterance.onend = resumeListening;
      utterance.onerror = resumeListening;
      window.speechSynthesis.speak(utterance);
      return;
    }

    fetch(`${API}/api/speak`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ text: answer }),
    }).catch(() => {});
  };

  const sendMessage = async (question = text) => {
    const cleanQuestion = question.trim();
    if (!cleanQuestion || isSending) return;

    setMessages((prev) => [
      ...prev,
      { from: "user", text: cleanQuestion },
    ]);
    setText("");
    setIsSending(true);

    try {
      const res = await fetch(`${API}/api/chat/${type}`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({ message: cleanQuestion, speak: false }),
      });

      const data = await res.json();
      if (!res.ok) {
        throw new Error(data.error || "The chatbot could not answer.");
      }

      setMessages((prev) => [...prev, { from: "bot", text: data.answer }]);
      speakAnswer(data.answer);
    } catch (error) {
      setMessages((prev) => [
        ...prev,
        {
          from: "bot",
          text:
            error instanceof TypeError
              ? "Backend not connected. Start the Flask server on port 5000."
              : error.message,
        },
      ]);
    } finally {
      setIsSending(false);
    }
  };

  const pauseListening = () => {
    stoppingRef.current = true;
    window.clearTimeout(restartTimerRef.current);
    const recognition = recognitionRef.current;
    recognitionRef.current = null;
    recognition?.abort();
    setIsListening(false);
  };

  const scheduleListenRestart = (delay) => {
    window.clearTimeout(restartTimerRef.current);
    restartTimerRef.current = window.setTimeout(() => {
      if (
        alwaysOnRef.current
        && !speakingRef.current
        && !recognitionRef.current
      ) {
        startRecognitionRef.current({ manual: false });
      }
    }, delay);
  };

  const handleHeardPhrase = (phrase) => {
    const heard = phrase.trim();
    if (!heard) return false;

    if (wakeWordOnlyRef.current) {
      const spoken = splitOnWakeWord(heard);
      if (!spoken) {
        setVoiceStatus(`Heard "${heard}". Say "care bot" first to ask me something.`);
        return false;
      }
      if (!spoken.question) {
        setVoiceStatus("Yes? Please ask your question.");
        return false;
      }
      setVoiceStatus(`Sending: "${spoken.question}"`);
      sendMessageRef.current(spoken.question);
      return true;
    }

    if (heard.split(/\s+/).length < 2) {
      setVoiceStatus(`Heard "${heard}". Waiting for a full question.`);
      return false;
    }

    setVoiceStatus(`Sending: "${heard}"`);
    sendMessageRef.current(heard);
    return true;
  };

  const startRecognition = ({ manual }) => {
    const SpeechRecognition =
      window.SpeechRecognition || window.webkitSpeechRecognition;

    if (!SpeechRecognition) {
      setVoiceStatus("Voice input is not supported in this browser. Use Chrome or Edge.");
      return;
    }

    if (speakingRef.current && !manual) return;

    window.clearTimeout(restartTimerRef.current);
    recognitionRef.current?.abort();

    const recognition = new SpeechRecognition();
    recognitionRef.current = recognition;
    stoppingRef.current = false;
    recognition.lang = "en-IN";
    recognition.interimResults = true;
    // Always-on keeps one long session; the button stays a single question.
    recognition.continuous = !manual;
    let finalTranscript = "";

    const sessionStartedAt = Date.now();

    recognition.onstart = () => {
      setIsListening(true);
      setVoiceStatus(
        manual
          ? "Listening... please speak your question."
          : wakeWordOnlyRef.current
            ? 'Always listening. Say "care bot" and then your question.'
            : "Always listening. Just ask your question.",
      );
    };

    recognition.onresult = (event) => {
      let liveTranscript = "";
      let sent = false;

      for (let index = event.resultIndex; index < event.results.length; index += 1) {
        const transcript = event.results[index][0].transcript;
        liveTranscript += transcript;
        if (event.results[index].isFinal) {
          if (manual) {
            finalTranscript += transcript;
          } else if (handleHeardPhrase(transcript)) {
            sent = true;
          }
        }
      }

      const heardText = (finalTranscript || liveTranscript).trim();
      if (!heardText || sent) return;

      if (manual) {
        setText(heardText);
        setVoiceStatus(`Heard: "${heardText}"`);
      } else {
        setVoiceStatus(`Hearing: "${liveTranscript.trim()}"`);
      }
    };

    recognition.onerror = (event) => {
      if (event.error === "not-allowed" || event.error === "service-not-allowed") {
        stoppingRef.current = true;
        setAlwaysOnPreference(false);
        setVoiceStatus("Microphone permission is blocked. Allow it in browser settings.");
        return;
      }

      // no-speech and aborted are normal in a long session; onend restarts.
      if (event.error !== "no-speech" && event.error !== "aborted") {
        setVoiceStatus(`Voice input error: ${event.error}. Please try again.`);
      }
    };

    recognition.onend = () => {
      setIsListening(false);
      if (recognitionRef.current === recognition) {
        recognitionRef.current = null;
      }

      if (manual) {
        const question = finalTranscript.trim();
        if (question) {
          setVoiceStatus(`Sending: "${question}"`);
          sendMessageRef.current(question);
        } else {
          setVoiceStatus((current) =>
            current.startsWith("Heard:")
              ? "Speech was not complete. Tap the microphone and try again."
              : current === "Listening... please speak your question."
                ? "No speech heard. Tap the microphone and try again."
                : current,
          );
        }
      }

      if (alwaysOnRef.current && !stoppingRef.current && !speakingRef.current) {
        // Chrome ends a session on its own after a silent stretch, so this
        // restarts it. A session that dies instantly means something is
        // wrong (no network, no service), so back off instead of spinning.
        if (Date.now() - sessionStartedAt < 1000) {
          restartDelayRef.current = Math.min(restartDelayRef.current * 2, 8000);
        } else {
          restartDelayRef.current = 400;
        }
        scheduleListenRestart(manual ? 900 : restartDelayRef.current);
      }
    };

    try {
      recognition.start();
    } catch {
      scheduleListenRestart(1000);
    }
  };

  const startListening = () => startRecognition({ manual: true });

  const setAlwaysOnPreference = (next) => {
    localStorage.setItem(`${ALWAYS_LISTEN_KEY}.${type}`, next ? "on" : "off");
    setAlwaysOn(next);
    if (!next) {
      pauseListening();
      setVoiceStatus("Always listening is off. Tap the microphone to speak.");
    }
  };

  const setWakeWordPreference = (next) => {
    localStorage.setItem(`${WAKE_WORD_KEY}.${type}`, next ? "on" : "off");
    setWakeWordOnly(next);
  };

  useEffect(() => {
    sendMessageRef.current = sendMessage;
    startRecognitionRef.current = startRecognition;
  });

  const askRandomQuestion = () => {
    const suggestions = CHAT_SUGGESTIONS[type];
    const question = suggestions[Math.floor(Math.random() * suggestions.length)];
    sendMessage(question);
  };

  return (
    <div className="panel chat-panel">
      <div className="panel-title">
        <MessageCircle size={20} />
        <h3>{title}</h3>
      </div>

      <div className="question-tools">
        <span>Try a question</span>
        <button
          className="random-question-btn"
          onClick={askRandomQuestion}
          disabled={isSending}
        >
          <Shuffle size={16} />
          Random question
        </button>
      </div>

      <div className="suggested-questions">
        {CHAT_SUGGESTIONS[type].map((question) => (
          <button
            key={question}
            onClick={() => sendMessage(question)}
            disabled={isSending}
          >
            {question}
          </button>
        ))}
      </div>

      <div className="chat-body" ref={chatBodyRef}>
        {messages.map((msg, index) => (
          <div key={index} className={`chat-msg ${msg.from}`}>
            {msg.text}
          </div>
        ))}
        {isSending && <div className="chat-msg bot pending">Thinking...</div>}
      </div>

      <div className="chat-input">
        <input
          value={text}
          placeholder="Type question..."
          onChange={(e) => setText(e.target.value)}
          onKeyDown={(e) => e.key === "Enter" && sendMessage()}
          disabled={isSending}
        />
        <button
          className={`voice-btn ${isListening ? "listening" : ""}`}
          onClick={startListening}
          disabled={isSending}
          title="Speak a question"
          aria-label="Speak a question"
        >
          <Mic size={18} />
        </button>
        <button onClick={() => sendMessage()} disabled={isSending}>
          <Send size={18} />
        </button>
      </div>
      <div className={`voice-status ${isListening ? "listening" : ""}`}>
        <span className="voice-pulse" />
        {voiceStatus}
      </div>

      <div className="voice-controls">
        <label className="voice-toggle">
          <input
            type="checkbox"
            checked={alwaysOn}
            onChange={(event) => setAlwaysOnPreference(event.target.checked)}
          />
          <span>Always listening (no need to tap the microphone)</span>
        </label>

        <select
          value={wakeWordOnly ? "wake" : "all"}
          onChange={(event) => setWakeWordPreference(event.target.value === "wake")}
          disabled={!alwaysOn}
        >
          <option value="wake">Answer after &quot;care bot&quot;</option>
          <option value="all">Answer everything I say</option>
        </select>
      </div>
    </div>
  );
}

