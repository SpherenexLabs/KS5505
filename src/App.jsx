function splitOnWakeWord(phrase) {
  const lower = phrase.toLowerCase();
  const wakeWord = WAKE_WORDS.find((word) => lower.includes(word));
  if (!wakeWord) return null;
  const question = phrase
    .slice(lower.indexOf(wakeWord) + wakeWord.length)
    .replace(/^[\s,.:;!?-]+/, "")
    .trim();
  return { wakeWord, question };
}

